import type { Note, Task } from "../types";
import { collectTagCounts, tagsOf } from "./tags";
import { excerpt } from "./util";

/**
 * 给外部智能体的只读快照格式。
 * 这个契约与 Lafei 内部 Dexie / 文件夹存储格式解耦，版本号独立演进。
 */
export const AGENT_SCHEMA_VERSION = 1;

export interface AgentFile {
  path: string;
  contents: string;
}

export interface AgentManifest {
  app: "lafei";
  schemaVersion: number;
  appVersion: string;
  generatedAt: string;
  revision: string;
  counts: {
    notes: number;
    tasks: number;
    openTasks: number;
    tags: number;
  };
  entrypoints: {
    notesIndex: string;
    tasks: string;
    tags: string;
    agents: string;
  };
}

interface AgentNoteIndexItem {
  id: string;
  title: string;
  tags: string[];
  pinned: boolean;
  createdAt: number;
  updatedAt: number;
  excerpt: string;
  file: string;
}

const PRIORITY_WEIGHT = { high: 3, medium: 2, low: 1 } as const;

function shortHash(value: string) {
  let hash = 0x811c9dc5;
  for (const char of value) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(36);
}

/** 文件名保持 ASCII 安全；原始 id 仍写在 frontmatter 与索引里 */
function agentNoteFile(id: string) {
  const safe = id.replace(/[^a-zA-Z0-9._-]/g, "_").replace(/^\.+/, "").slice(0, 96);
  return `notes/${safe || "note"}-${shortHash(id)}.md`;
}

function revisionOf(notes: Note[], tasks: Task[]) {
  const entries = [
    ...notes.map(
      (note) => `n:${note.id}:${note.updatedAt}:${note.pinned ? 1 : 0}:${tagsOf(note).join(",")}`,
    ),
    ...tasks.map(
      (task) =>
        `t:${task.id}:${task.updatedAt}:${task.done ? 1 : 0}:${task.dueDate ?? ""}:${tagsOf(task).join(",")}`,
    ),
  ].sort();
  let hash = 0x811c9dc5;
  for (const char of entries.join("|")) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 0x01000193);
  }
  const latest = Math.max(
    0,
    ...notes.map((note) => note.updatedAt),
    ...tasks.map((task) => task.updatedAt),
  );
  return `${latest}-${(hash >>> 0).toString(16)}`;
}

function agentNoteMarkdown(note: Note) {
  const header = [
    "---",
    `id: ${JSON.stringify(note.id)}`,
    `title: ${JSON.stringify(note.title)}`,
    `tags: ${JSON.stringify(tagsOf(note))}`,
    `pinned: ${note.pinned ? "true" : "false"}`,
    `createdAt: ${note.createdAt}`,
    `updatedAt: ${note.updatedAt}`,
    "---",
  ].join("\n");
  return `${header}\n\n${note.content}`;
}

function agentTaskRecord(task: Task) {
  return {
    id: task.id,
    title: task.title,
    description: task.description,
    noteId: task.noteId,
    dueDate: task.dueDate,
    priority: task.priority,
    tags: tagsOf(task),
    done: task.done,
    completedAt: task.completedAt,
    createdAt: task.createdAt,
    updatedAt: task.updatedAt,
  };
}

function agentTaskOrder(a: Task, b: Task) {
  if (a.done !== b.done) return a.done ? 1 : -1;
  const aDue = a.dueDate ?? "9999-12-31";
  const bDue = b.dueDate ?? "9999-12-31";
  if (aDue !== bDue) return aDue.localeCompare(bDue);
  return (
    PRIORITY_WEIGHT[b.priority] - PRIORITY_WEIGHT[a.priority] ||
    b.updatedAt - a.updatedAt
  );
}

function agentsMarkdown(appVersion: string, generatedAt: string) {
  return `# Lafei agent snapshot

This directory is a **read-only** export from Lafei ${appVersion}, generated at ${generatedAt}.
It contains the user's notes and tasks. Do not edit these files; changes here are not written
back to Lafei.

## Start here

1. Read \`manifest.json\` for the schema version, revision and counts.
2. Use \`notes.index.json\` to find notes without reading every file.
3. Use \`tasks.jsonl\` for one JSON task per line.
4. Use \`tags.json\` to map tags to notes and tasks.
5. Read the \`file\` path from \`notes.index.json\` for a note's full Markdown.

## Conventions

- Note ids are stable strings; the Markdown frontmatter repeats \`id\`, \`title\`, \`tags\`,
  \`pinned\`, \`createdAt\` and \`updatedAt\`.
- Tasks use \`done: true|false\` for status, ISO dates (\`YYYY-MM-DD\`) for \`dueDate\`,
  and \`priority: "high" | "medium" | "low"\`.
- Tags are plain strings without the leading \`#\`.
- Files are regenerated by Lafei and may change between calls; check \`manifest.json\`'s
  \`revision\` before relying on cached content.

## Prefer MCP

If the user configured \`lafei-mcp\`, use its tools instead of parsing files:

- \`notes_search\` — search notes by title/tags/content
- \`notes_get\` — read a note by id
- \`tasks_list\` — list tasks filtered by status/tag/due date
- \`tasks_get\` — read a task by id
- \`tags_list\` — list tags with note/task counts

The MCP server is read-only. Never invent note ids or task states; quote the source content
when the user asks about their notes.
`;
}

/**
 * 从当前笔记和任务构建完整的只读快照文件列表。
 * 纯函数，方便单测和在不启动 Tauri 的情况下复用。
 */
export function buildAgentSnapshot(
  notes: Note[],
  tasks: Task[],
  appVersion: string,
  now = Date.now(),
): AgentFile[] {
  const generatedAt = new Date(now).toISOString();
  const sortedNotes = [...notes].sort((a, b) => b.updatedAt - a.updatedAt);
  const sortedTasks = [...tasks].sort(agentTaskOrder);
  const tagCounts = collectTagCounts(notes, tasks);
  const openTasks = tasks.filter((task) => !task.done).length;

  const notesIndex: AgentNoteIndexItem[] = sortedNotes.map((note) => ({
    id: note.id,
    title: note.title,
    tags: tagsOf(note),
    pinned: note.pinned,
    createdAt: note.createdAt,
    updatedAt: note.updatedAt,
    excerpt: excerpt(note.content, 180),
    file: agentNoteFile(note.id),
  }));

  const manifest: AgentManifest = {
    app: "lafei",
    schemaVersion: AGENT_SCHEMA_VERSION,
    appVersion,
    generatedAt,
    revision: revisionOf(notes, tasks),
    counts: {
      notes: notes.length,
      tasks: tasks.length,
      openTasks,
      tags: tagCounts.length,
    },
    entrypoints: {
      notesIndex: "notes.index.json",
      tasks: "tasks.jsonl",
      tags: "tags.json",
      agents: "AGENTS.md",
    },
  };

  return [
    { path: "manifest.json", contents: `${JSON.stringify(manifest, null, 2)}\n` },
    { path: "AGENTS.md", contents: agentsMarkdown(appVersion, generatedAt) },
    { path: "notes.index.json", contents: `${JSON.stringify(notesIndex, null, 2)}\n` },
    {
      path: "tasks.jsonl",
      contents: sortedTasks.map((task) => JSON.stringify(agentTaskRecord(task))).join("\n") + (sortedTasks.length ? "\n" : ""),
    },
    { path: "tags.json", contents: `${JSON.stringify(tagCounts, null, 2)}\n` },
    ...sortedNotes.map((note) => ({
      path: agentNoteFile(note.id),
      contents: agentNoteMarkdown(note),
    })),
  ];
}
